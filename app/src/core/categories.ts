/**
 * 상호명에서 범주를 추측한다. 짚이는 게 없으면 "기타".
 */
export function guessCategory(merchant: string): string {
  const s = (merchant ?? "").trim();
  if (!s) return "기타";
  for (const [re, category] of CATEGORY_HINTS) {
    if (re.test(s)) return category;
  }
  return "기타";
}
